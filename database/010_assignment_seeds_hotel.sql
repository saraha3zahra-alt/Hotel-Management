-- ===========================================================================
-- ANALYTICAL VIEWS FOR HOTEL SALES ANALYST
-- ===========================================================================

CREATE OR REPLACE VIEW view_hotel_sales_analytics AS
SELECT 
    r.reservation_id,
    r.reservation_number,
    r.check_in_date,
    r.check_out_date,
    DATE_TRUNC('month', r.check_in_date)::DATE AS stay_month,
    s.status_name,
    r.booking_source,
    c.customer_id,
    (c.first_name || ' ' || c.last_name) AS customer_name,
    c.nationality AS city,
    r.gross_amount,
    r.discount_amount,
    COALESCE(rf.refund_amount, 0) AS refund_amount,
    (r.final_amount - COALESCE(rf.refund_amount, 0)) AS net_amount
FROM reservations r
JOIN reservation_statuses s ON r.status_id = s.status_id
JOIN customers c ON r.customer_id = c.customer_id
LEFT JOIN (
    SELECT reservation_id, SUM(refund_amount) AS refund_amount 
    FROM refunds 
    WHERE status IN ('APPROVED', 'PROCESSED') 
    GROUP BY reservation_id
) rf ON r.reservation_id = rf.reservation_id
WHERE s.status_code <> 'CANCELLED';

CREATE OR REPLACE FUNCTION get_hotel_sales_kpis(target_year INT DEFAULT 2026)
RETURNS TABLE (
    month_name TEXT,
    month_date DATE,
    total_reservations BIGINT,
    gross_sales NUMERIC,
    total_discounts NUMERIC,
    total_refunds NUMERIC,
    net_sales NUMERIC,
    aov NUMERIC
) LANGUAGE plpgsql AS $$
BEGIN
    RETURN QUERY
    SELECT 
        TO_CHAR(stay_month, 'YYYY-MM') AS month_name,
        stay_month AS month_date,
        COUNT(DISTINCT reservation_id) AS total_reservations,
        ROUND(COALESCE(SUM(gross_amount), 0), 2) AS gross_sales,
        ROUND(COALESCE(SUM(discount_amount), 0), 2) AS total_discounts,
        ROUND(COALESCE(SUM(refund_amount), 0), 2) AS total_refunds,
        ROUND(COALESCE(SUM(net_amount), 0), 2) AS net_sales,
        ROUND(COALESCE(SUM(net_amount) / NULLIF(COUNT(DISTINCT reservation_id), 0), 0), 2) AS aov
    FROM view_hotel_sales_analytics
    WHERE EXTRACT(YEAR FROM stay_month) = target_year
    GROUP BY stay_month
    ORDER BY stay_month;
END;
$$;
