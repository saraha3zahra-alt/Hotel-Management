CREATE OR REPLACE VIEW view_hotel_sales_summary AS
SELECT 
    r.reservation_id,
    r.reservation_number,
    r.check_in_date,
    DATE_TRUNC('month', r.check_in_date)::DATE AS reservation_month,
    r.status_id,
    s.status_name,
    r.booking_source,
    c.customer_id,
    (c.first_name || ' ' || c.last_name) AS customer_name,
    c.nationality AS city_or_nationality,
    r.gross_amount,
    r.discount_amount,
    r.final_amount AS net_amount
FROM reservations r
JOIN customers c ON r.customer_id = c.customer_id
JOIN reservation_statuses s ON r.status_id = s.status_id
WHERE s.status_code <> 'CANCELLED';

CREATE OR REPLACE FUNCTION get_monthly_hotel_kpis(target_year INT DEFAULT 2026)
RETURNS TABLE (
    month_name TEXT,
    month_date DATE,
    total_reservations BIGINT,
    gross_revenue NUMERIC,
    total_discounts NUMERIC,
    net_revenue NUMERIC,
    adr NUMERIC
) LANGUAGE plpgsql AS $$
BEGIN
    RETURN QUERY
    SELECT 
        TO_CHAR(reservation_month, 'YYYY-MM') AS month_name,
        reservation_month AS month_date,
        COUNT(DISTINCT reservation_id) AS total_reservations,
        ROUND(COALESCE(SUM(gross_amount), 0), 2) AS gross_revenue,
        ROUND(COALESCE(SUM(discount_amount), 0), 2) AS total_discounts,
        ROUND(COALESCE(SUM(net_amount), 0), 2) AS net_revenue,
        ROUND(COALESCE(SUM(net_amount) / NULLIF(COUNT(DISTINCT reservation_id), 0), 0), 2) AS adr
    FROM view_hotel_sales_summary
    WHERE EXTRACT(YEAR FROM reservation_month) = target_year
    GROUP BY reservation_month
    ORDER BY reservation_month;
END;
$$;
