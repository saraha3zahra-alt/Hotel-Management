CREATE OR REPLACE VIEW view_sales_summary AS
SELECT 
    o.order_id,
    o.order_date,
    DATE_TRUNC('month', o.order_date)::DATE AS order_month,
    o.status,
    o.sales_channel,
    o.branch,
    c.customer_id,
    c.customer_name,
    c.city,
    SUM(i.quantity * i.unit_price) AS gross_amount,
    SUM(i.discount_amount) AS discount_amount,
    SUM(i.refund_amount) AS refund_amount,
    SUM((i.quantity * i.unit_price) - i.discount_amount - i.refund_amount) AS net_amount
FROM orders o
JOIN customers c ON o.customer_id = c.customer_id
JOIN order_items i ON o.order_id = i.order_id
WHERE o.status <> 'CANCELLED'
GROUP BY o.order_id, o.order_date, o.status, o.sales_channel, o.branch, c.customer_id, c.customer_name, c.city;

-- Function for n8n RPC tool: Get Monthly KPI Summary
CREATE OR REPLACE FUNCTION get_monthly_sales_kpis(target_year INT DEFAULT 2026)
RETURNS TABLE (
    month_name TEXT,
    month_date DATE,
    total_orders BIGINT,
    gross_sales NUMERIC,
    total_discounts NUMERIC,
    total_refunds NUMERIC,
    net_sales NUMERIC,
    aov NUMERIC
) LANGUAGE plpgsql AS $$
BEGIN
    RETURN QUERY
    SELECT 
        TO_CHAR(order_month, 'YYYY-MM') AS month_name,
        order_month AS month_date,
        COUNT(DISTINCT order_id) AS total_orders,
        ROUND(COALESCE(SUM(gross_amount), 0), 2) AS gross_sales,
        ROUND(COALESCE(SUM(discount_amount), 0), 2) AS total_discounts,
        ROUND(COALESCE(SUM(refund_amount), 0), 2) AS total_refunds,
        ROUND(COALESCE(SUM(net_amount), 0), 2) AS net_sales,
        ROUND(COALESCE(SUM(net_amount) / NULLIF(COUNT(DISTINCT order_id), 0), 0), 2) AS aov
    FROM view_sales_summary
    WHERE EXTRACT(YEAR FROM order_month) = target_year
    GROUP BY order_month
    ORDER BY order_month;
END;
$$;
