-- PHASE 1: Database Tables + Core Constraints
-- Business baseline:
-- 1 reservation -> many reservation_rooms
-- price = guest x night
-- discount tier is evaluated per reservation_room
-- room blocks participate in availability

-- HOTEL / ROOM CONFIGURATION
create table hotels (
 hotel_id bigint generated by default as identity primary key,
 hotel_code varchar(20) not null unique,
 hotel_name varchar(150) not null,
 address text, phone varchar(30), email varchar(150),
 currency_code varchar(3) not null default 'EGP',
 timezone varchar(50) not null default 'Africa/Cairo',
 is_active boolean not null default true,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);

create table buildings (
 building_id bigint generated by default as identity primary key,
 hotel_id bigint not null references hotels(hotel_id),
 building_code varchar(20) not null,
 building_name varchar(100) not null,
 description text, is_active boolean not null default true,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 unique(hotel_id, building_code)
);

create table pricing_locations (
 pricing_location_id bigint generated by default as identity primary key,
 location_code varchar(20) not null unique,
 location_name varchar(100) not null,
 description text, is_active boolean not null default true
);

create table floors (
 floor_id bigint generated by default as identity primary key,
 building_id bigint not null references buildings(building_id),
 pricing_location_id bigint not null references pricing_locations(pricing_location_id),
 floor_code varchar(20) not null, floor_name varchar(100) not null,
 floor_number integer not null, is_active boolean not null default true,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 unique(building_id,floor_code), unique(building_id,floor_number)
);

create table room_types (
 room_type_id bigint generated by default as identity primary key,
 room_type_code varchar(20) not null unique,
 room_type_name varchar(100) not null,
 max_occupancy integer not null check(max_occupancy>0),
 max_adults integer not null check(max_adults>=0),
 max_children integer not null check(max_children>=0),
 description text, is_active boolean not null default true,
 check(max_adults<=max_occupancy), check(max_children<=max_occupancy)
);

create table room_operational_statuses (
 status_id smallint generated by default as identity primary key,
 status_code varchar(30) not null unique,
 status_name varchar(100) not null,
 is_sellable boolean not null default false
);

create table rooms (
 room_id bigint generated by default as identity primary key,
 floor_id bigint not null references floors(floor_id),
 room_type_id bigint not null references room_types(room_type_id),
 operational_status_id smallint not null references room_operational_statuses(status_id),
 room_number varchar(30) not null, description text, notes text,
 is_active boolean not null default true,
 created_at timestamptz not null default now(), created_by uuid,
 updated_at timestamptz not null default now(), updated_by uuid
);

create or replace function enforce_room_number_unique_per_building()
returns trigger language plpgsql as $$
begin
 if exists(
  select 1 from rooms r
  join floors rf on rf.floor_id=r.floor_id
  join floors nf on nf.floor_id=new.floor_id
  where rf.building_id=nf.building_id and r.room_number=new.room_number
    and r.room_id<>coalesce(new.room_id,-1)
 ) then raise exception 'Room number % already exists in this building',new.room_number; end if;
 return new;
end $$;
create trigger trg_rooms_unique_number_per_building
before insert or update of floor_id,room_number on rooms
for each row execute function enforce_room_number_unique_per_building();

create table room_block_reasons (
 block_reason_id bigint generated by default as identity primary key,
 reason_code varchar(30) not null unique, reason_name varchar(100) not null,
 is_active boolean not null default true
);
create table room_blocks (
 room_block_id bigint generated by default as identity primary key,
 room_id bigint not null references rooms(room_id),
 block_reason_id bigint not null references room_block_reasons(block_reason_id),
 start_date date not null, end_date date not null, notes text,
 created_by uuid, created_at timestamptz not null default now(),
 check(end_date>start_date)
);

-- CUSTOMERS / RESERVATIONS
