-- PROMOTIONS: discount is per reservation_room
create table promotions (
 promotion_id bigint generated by default as identity primary key,
 hotel_id bigint not null references hotels(hotel_id),
 promotion_code varchar(30) not null,promotion_name varchar(150) not null,description text,
 valid_from date not null,valid_to date not null,discount_scope varchar(30) not null default 'ROOM',
 priority integer not null default 0,can_combine boolean not null default false,
 is_active boolean not null default true,created_by uuid,created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),unique(hotel_id,promotion_code),
 check(valid_to>=valid_from),check(discount_scope='ROOM')
);
create table promotion_tiers (
 promotion_tier_id bigint generated by default as identity primary key,
 promotion_id bigint not null references promotions(promotion_id) on delete cascade,
 min_nights integer not null check(min_nights>=1),max_nights integer,
 discount_type varchar(20) not null check(discount_type in('PERCENTAGE','FIXED_AMOUNT')),
 discount_value numeric(18,2) not null check(discount_value>=0),
 check(max_nights is null or max_nights>=min_nights),
 check(discount_type<>'PERCENTAGE' or discount_value<=100)
);
alter table promotion_tiers add constraint ex_promotion_tiers_no_overlap
exclude using gist(promotion_id with =,int4range(min_nights,coalesce(max_nights+1,2147483647),'[)') with &&);

create table promotion_room_types(
 promotion_id bigint references promotions(promotion_id) on delete cascade,
