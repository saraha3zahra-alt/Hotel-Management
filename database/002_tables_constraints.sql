-- CORE GUARDS
create or replace function validate_reservation_room_capacity()
returns trigger language plpgsql as $$
declare a int;c int;o int;
begin
 select rt.max_adults,rt.max_children,rt.max_occupancy into a,c,o
 from rooms r join room_types rt on rt.room_type_id=r.room_type_id where r.room_id=new.room_id;
 if new.adults_count>a or new.children_count>c or new.adults_count+new.children_count>o
 then raise exception 'Room capacity exceeded'; end if;
 return new;
end $$;
create trigger trg_validate_capacity before insert or update of room_id,adults_count,children_count
on reservation_rooms for each row execute function validate_reservation_room_capacity();

create or replace function prevent_double_booking()
returns trigger language plpgsql as $$
declare b boolean;
begin
 select rs.blocks_inventory into b from reservations r join reservation_statuses rs on rs.status_id=r.status_id where r.reservation_id=new.reservation_id;
 if coalesce(b,false) and exists(
  select 1 from reservation_rooms rr join reservations r on r.reservation_id=rr.reservation_id
  join reservation_statuses rs on rs.status_id=r.status_id
  where rr.room_id=new.room_id and rr.reservation_room_id<>coalesce(new.reservation_room_id,-1)
  and rs.blocks_inventory and daterange(rr.check_in_date,rr.check_out_date,'[)') && daterange(new.check_in_date,new.check_out_date,'[)')
 ) then raise exception 'Room already reserved for requested dates'; end if;
 if exists(select 1 from room_blocks rb where rb.room_id=new.room_id
  and daterange(rb.start_date,rb.end_date,'[)') && daterange(new.check_in_date,new.check_out_date,'[)'))
 then raise exception 'Room blocked for requested dates'; end if;
 return new;
end $$;
create trigger trg_prevent_double_booking before insert or update of room_id,check_in_date,check_out_date,reservation_id
on reservation_rooms for each row execute function prevent_double_booking();

create or replace function prevent_room_block_conflict()
returns trigger language plpgsql as $$
begin
 if exists(
  select 1 from reservation_rooms rr join reservations r on r.reservation_id=rr.reservation_id
  join reservation_statuses rs on rs.status_id=r.status_id
  where rr.room_id=new.room_id and rs.blocks_inventory
  and daterange(rr.check_in_date,rr.check_out_date,'[)') && daterange(new.start_date,new.end_date,'[)')
 ) then raise exception 'Room block overlaps an active reservation'; end if;
 return new;
end $$;
create trigger trg_prevent_room_block_conflict before insert or update of room_id,start_date,end_date
on room_blocks for each row execute function prevent_room_block_conflict();

create or replace function validate_refund_amount()
returns trigger language plpgsql as $$
declare p numeric(18,2);r numeric(18,2);
begin
 select coalesce(sum(amount),0) into p from payments where reservation_id=new.reservation_id and status='SUCCESSFUL';
 select coalesce(sum(refund_amount),0) into r from refunds where reservation_id=new.reservation_id
 and refund_id<>coalesce(new.refund_id,-1) and status in('APPROVED','PROCESSED');
 if new.status in('APPROVED','PROCESSED') and new.refund_amount>p-r
 then raise exception 'Refund exceeds refundable paid amount'; end if;
 return new;
end $$;
create trigger trg_validate_refund before insert or update of refund_amount,status,reservation_id
on refunds for each row execute function validate_refund_amount();

